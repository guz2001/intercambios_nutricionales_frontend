/* Busca un alimento por su ID */
export function obtenerMockPorId(id) {
  return alimentos.find((a) => a.id === Number(id)) || null;
}

/* Filtra alimentos según parámetros de búsqueda */
export function filtrarMocks({ q = '', grupo_id = '', poblacion = '' }) {
  return alimentos.filter((a) => {
    const coincideTexto =
      !q || a.nombre.toLowerCase().includes(q.toLowerCase());

    const coincideGrupo =
      !grupo_id || a.grupo.id === Number(grupo_id);

    /* "ninos_y_adultos" aparece en todos los grupos de población */
    const coincidePoblacion =
      !poblacion ||
      a.poblacion === poblacion ||
      a.poblacion === 'niños_y_adultos';

    return coincideTexto && coincideGrupo && coincidePoblacion;
  });
}
